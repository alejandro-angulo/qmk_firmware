uint16_t last_keypress_time = 0;

static void setup_animation_decay_constants(void) {
    if (multiplier != 0) {
        // Constants already determined, no need to derive again
        return;
    }

    const int max_wpm = 255;  // get_current_wpm max return value is 255
    base = pow(
        (double) (ANIM_FRAME_DURATION_MIN / ANIM_FRAME_DURATION_MAX),
        (double) 1 / (max_wpm - TAP_SPEED)
    );
    multiplier = ANIM_FRAME_DURATION_MAX * pow(base, -1.0 * TAP_SPEED);
}

